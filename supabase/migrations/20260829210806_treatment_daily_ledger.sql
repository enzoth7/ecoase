alter table public.products
  add column if not exists requires_treatment boolean not null default false;

update public.products
set requires_treatment = treatment in ('Marcado', 'HT', 'Marcado y HT')
where treatment is not null;

alter table public.orders drop constraint if exists orders_required_operations_check;

update public.orders
set required_operations = array(
  select distinct case when operation in ('marking', 'ht') then 'treatment' else operation end
  from unnest(coalesce(required_operations, array['assembly']::text[])) operation
  order by 1
)
where coalesce(required_operations, array[]::text[]) && array['marking', 'ht']::text[];

alter table public.orders add constraint orders_required_operations_check
  check (cardinality(required_operations) > 0 and required_operations <@ array['assembly', 'treatment']::text[]);

create table public.treatment_batches (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete restrict,
  client_product_id bigint references public.client_products(id) on delete restrict,
  order_line_id text references public.order_lines(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  performed_at timestamptz not null,
  responsible text not null check (nullif(trim(responsible), '') is not null),
  status text not null check (status in ('posted', 'rejected', 'reversal')),
  note text,
  reversal_of_batch_id bigint unique references public.treatment_batches(id) on delete restrict,
  created_at timestamptz not null default now(),
  check ((status = 'reversal') = (reversal_of_batch_id is not null)),
  check (status = 'posted' or nullif(trim(note), '') is not null),
  check (client_product_id is not null or nullif(trim(note), '') is not null)
);

create table public.treatment_control_checks (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.treatment_batches(id) on delete restrict,
  control_id bigint not null references public.client_product_controls(id) on delete restrict,
  control_title_snapshot text not null check (nullif(trim(control_title_snapshot), '') is not null),
  result text not null check (result in ('pass', 'fail')),
  note text,
  created_at timestamptz not null default now(),
  unique (batch_id, control_id),
  check (result = 'pass' or nullif(trim(note), '') is not null)
);

create table public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete restrict,
  stock_state text not null check (stock_state in ('pending_treatment', 'ready')),
  quantity integer not null check (quantity <> 0),
  movement_type text not null check (movement_type in (
    'production_receipt', 'treatment_out', 'treatment_in',
    'treatment_reversal_out', 'treatment_reversal_in'
  )),
  treatment_batch_id bigint references public.treatment_batches(id) on delete restrict,
  production_allocation_id bigint references public.production_allocations(id) on delete restrict,
  transformation_id uuid not null default gen_random_uuid(),
  performed_at timestamptz not null,
  responsible text not null check (nullif(trim(responsible), '') is not null),
  note text,
  correction_of_movement_id bigint references public.stock_movements(id) on delete restrict,
  created_at timestamptz not null default now(),
  check (
    (movement_type = 'production_receipt' and quantity > 0 and treatment_batch_id is null and production_allocation_id is not null)
    or (movement_type = 'treatment_out' and stock_state = 'pending_treatment' and quantity < 0 and treatment_batch_id is not null)
    or (movement_type = 'treatment_in' and stock_state = 'ready' and quantity > 0 and treatment_batch_id is not null)
    or (movement_type = 'treatment_reversal_out' and stock_state = 'ready' and quantity < 0 and treatment_batch_id is not null)
    or (movement_type = 'treatment_reversal_in' and stock_state = 'pending_treatment' and quantity > 0 and treatment_batch_id is not null)
  )
);

