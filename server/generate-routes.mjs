import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../app/api/", import.meta.url));
const destination = fileURLToPath(new URL("./route-map.ts", import.meta.url));

function visit(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return visit(path);
    return entry.name === "route.ts" ? [path] : [];
  });
}

export function generateRoutes() {
  const routes = visit(root).sort((left, right) => {
    const dynamicCount = (value) => (value.match(/\[[^/]+\]/g) || []).length;
    return dynamicCount(left) - dynamicCount(right) || left.localeCompare(right);
  }).map((path) => {
    const parts = relative(root, dirname(path)).split(sep);
    const keys = parts.filter((part) => /^\[.+\]$/.test(part)).map((part) => part.slice(1, -1));
    const pattern = `^/api/${parts.map((part) => /^\[.+\]$/.test(part) ? "([^/]+)" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("/")}$`;
    const importPath = `../app/api/${parts.join("/")}/route`;
    return `  { pattern: new RegExp(${JSON.stringify(pattern)}), keys: ${JSON.stringify(keys)}, load: () => import(${JSON.stringify(importPath)}) },`;
  });
  routes.push('  { pattern: /^\\/mcp$/, keys: [], load: () => import("../app/mcp/route") },');
  // OAuth para que Claude (celular y web) pueda conectarse al MCP.
  routes.push('  { pattern: /^\\/oauth\\/authorize$/, keys: [], load: () => import("../app/oauth/authorize/route") },');
  routes.push('  { pattern: /^\\/oauth\\/token$/, keys: [], load: () => import("../app/oauth/token/route") },');
  routes.push('  { pattern: /^\\/oauth\\/register$/, keys: [], load: () => import("../app/oauth/register/route") },');
  routes.push('  { pattern: /^\\/\\.well-known\\/(oauth-authorization-server|openid-configuration)(\\/.*)?$/, keys: [], load: () => import("../app/oauth/well-known-authorization-server/route") },');
  routes.push('  { pattern: /^\\/\\.well-known\\/oauth-protected-resource(\\/.*)?$/, keys: [], load: () => import("../app/oauth/well-known-protected-resource/route") },');

  const source = `// Generated by server/generate-routes.mjs. Do not edit by hand.\nexport const routes = [\n${routes.join("\n")}\n];\n`;
  if (!existsSync(destination) || readFileSync(destination, "utf8") !== source) writeFileSync(destination, source);
}

generateRoutes();
